// Builds js/place-postcard.js from the "Postcard Description (EN/ZH)" columns of
// the migration-place-descriptions CSV. Those short lines are what the foldable
// A4 (print-a4.html) shows under each origin place; the on-screen migration map
// keeps using the longer descriptions in js/migration-theme.js.
//
//   node scripts/build-place-postcard.js "C:\path\to\migration-place-descriptions_postcard.csv"
const fs = require("fs");
const path = require("path");

const csvPath = process.argv[2];
if (!csvPath) {
  console.error("usage: node scripts/build-place-postcard.js <csv>");
  process.exit(1);
}

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  text = text.replace(/^\uFEFF/, "");
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.length > 1 || row[0] !== "") rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const rows = parseCsv(fs.readFileSync(csvPath, "utf8"));
const head = rows[0];
const col = (name) => {
  const i = head.indexOf(name);
  if (i < 0) throw new Error("column not found: " + name);
  return i;
};
const iKey = col("Key"), iEn = col("Postcard Description (EN)"), iZh = col("Postcard Description (ZH)");

const out = {};
rows.slice(1).forEach((r) => {
  const key = (r[iKey] || "").trim();
  if (!key) return;
  const en = (r[iEn] || "").trim(), zh = (r[iZh] || "").trim();
  if (!en || !zh) throw new Error("missing postcard description for " + key);
  out[key] = { en, zh };
});

const js =
  "// Generated by scripts/build-place-postcard.js from the migration-place-descriptions\n" +
  "// CSV (columns \"Postcard Description (EN/ZH)\"). Do not hand-edit — re-run the script.\n" +
  "// Short, per-place lines for the foldable A4 (js/print-a4.js). The on-screen\n" +
  "// migration map keeps its own longer text in js/migration-theme.js.\n" +
  "const PLACE_POSTCARD = " + JSON.stringify(out, null, 2) + ";\n\n" +
  "function getPlacePostcard(place, lang) {\n" +
  "  const d = PLACE_POSTCARD[place.key] || PLACE_POSTCARD.other;\n" +
  "  return lang === \"zh\" ? d.zh : d.en;\n" +
  "}\n";
fs.writeFileSync(path.join(__dirname, "..", "js", "place-postcard.js"), js);
console.log("wrote js/place-postcard.js with " + Object.keys(out).length + " places");
