// One-off build step: converts the OOY-supplied CSV of Chinese clan
// surnames into js/surname-data.js, a plain JS array the kiosk can use
// directly (same reasoning as places.js / survey-questions.js — the kiosk
// runs fully offline over file://, so data is baked into a <script> rather
// than fetched at runtime). Re-run this with `node scripts/build-surnames.js
// <path-to-csv>` whenever OOY sends an updated CSV.
const fs = require("fs");
const path = require("path");

const csvPath = process.argv[2];
if (!csvPath) {
  console.error("Usage: node scripts/build-surnames.js <path-to-csv>");
  process.exit(1);
}
const raw = fs.readFileSync(csvPath, "utf8");

// Minimal RFC4180 CSV parser: handles quoted fields with embedded commas,
// newlines, and doubled "" escapes. Good enough for this one file; not a
// general-purpose library.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;
  let i = 0;
  const n = text.length;
  while (i < n) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i += 2;
          continue;
        }
        inQuotes = false;
        i++;
        continue;
      }
      field += c;
      i++;
      continue;
    }
    if (c === '"') {
      inQuotes = true;
      i++;
      continue;
    }
    if (c === ",") {
      row.push(field);
      field = "";
      i++;
      continue;
    }
    if (c === "\r") {
      i++;
      continue;
    }
    if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
      i++;
      continue;
    }
    field += c;
    i++;
  }
  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

const rows = parseCsv(raw);
const header = rows[0].map((h) => h.trim());
const col = (name) => header.indexOf(name);
const iEn = col("Surname in English");
const iZh = col("Surname in Chinese");
const iHistory = col("History / Origin of the surname");
const iHistoryZh = col("History / Origin of the surname (Chinese)");
const iFamous = col("Famous person of the clan");
const iFamousZh = col("Famous person of the clan (Chinese)");
const iVariants = col("Spelling variants");

function stripDiacritics(s) {
  return s.normalize("NFD").replace(/[̀-ͯ]/g, "");
}
function normalizeSpelling(s) {
  return stripDiacritics(s).toUpperCase().replace(/[^A-Z]/g, "");
}
// "Heng, 新加坡 (Singapore)" / "Ding (Mandarin)" / "Đinh, Vietnam" -> "Heng" / "Ding" / "Đinh"
function extractSpelling(variant) {
  let v = variant.trim();
  v = v.replace(/\([^)]*\)\s*$/, "").trim();
  v = v.split(",")[0].trim();
  return v;
}

const records = [];
for (let r = 1; r < rows.length; r++) {
  const row = rows[r];
  if (!row || row.every((c) => !c || !c.trim())) continue;
  const en = (row[iEn] || "").trim();
  const zh = (row[iZh] || "").trim();
  if (!en || !zh) continue;
  const history = (row[iHistory] || "").trim();
  const historyZh = iHistoryZh >= 0 ? (row[iHistoryZh] || "").trim() : "";
  const famous = (row[iFamous] || "").trim();
  const famousZh = iFamousZh >= 0 ? (row[iFamousZh] || "").trim() : "";
  const variantsRaw = (row[iVariants] || "").trim();
  const spellings = new Set();
  spellings.add(extractSpelling(en));
  if (variantsRaw) {
    variantsRaw
      .split("\n")
      .map((s) => s.trim())
      .filter(Boolean)
      .forEach((v) => {
        const sp = extractSpelling(v);
        if (sp) spellings.add(sp);
      });
  }
  records.push({
    en,
    zh,
    history,
    historyZh,
    famous,
    famousZh,
    spellings: Array.from(spellings),
  });
}

// Build spelling -> [record index] lookup (case/diacritic-insensitive) so
// the kiosk can find every Chinese surname a given romanization could mean.
const lookup = {};
records.forEach((rec, idx) => {
  rec.spellings.forEach((sp) => {
    const key = normalizeSpelling(sp);
    if (!key) return;
    if (!lookup[key]) lookup[key] = [];
    if (!lookup[key].includes(idx)) lookup[key].push(idx);
  });
});

const out = `// Generated by scripts/build-surnames.js from OOY's surname CSV.
// Do not hand-edit — re-run the script against an updated CSV instead.
// SURNAME_RECORDS: one entry per distinct Chinese surname, with every
// Western spelling (dialect/country variants included) that can romanize
// to it, plus history/historyZh (English/Chinese origin text — historyZh is
// often blank, see js/surname-card.js for the fallback this triggers).
// SURNAME_LOOKUP maps a normalized (diacritic/case-stripped) spelling to the
// indices of every SURNAME_RECORDS entry it could mean — several entries for
// an ambiguous spelling like "Low" (劉/羅/...), one for most.
const SURNAME_RECORDS = ${JSON.stringify(records, null, 2)};

const SURNAME_LOOKUP = ${JSON.stringify(lookup, null, 2)};
`;

const outPath = path.join(__dirname, "..", "js", "surname-data.js");
fs.writeFileSync(outPath, out, "utf8");
console.log(`Wrote ${records.length} surname records (${Object.keys(lookup).length} distinct spellings) to ${outPath}`);
